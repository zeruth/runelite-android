#!/usr/bin/env python3
"""Bootstrap fixtures through the hub dexer's transform and D8, and the APK link probe.

With no arguments this is the host check (card #95): one fixture class per invokedynamic and
dynamic-constant bootstrap kind is compiled, its bootstraps are confirmed with indy-inventory.py,
it runs on the host JVM, goes through PluginClassTransform (the pass PluginDexer runs before D8),
runs again under -Xverify:all with the same output, and is dexed by D8 at min-api 26; the dex must
hold no call site and no method handle, the two things ART at API 26 cannot link. The client lambda
pass (DesugarLambdasTask's private-method lowering) gets the same treatment through
TestClientLambdaLowering. The JdkRetargets fixture (card #93, TestRuntimeRetargetPlugin) goes
through PluginClassTransform too, TestRuntimeRetarget checks no table member is left, and the
rewritten plugin runs on the host JVM against the shims and the desktop regex engine.

With --apk and --serial, it also links a desktop-compiled plugin and the retargeted fixture
against the exact APK using its compiler assets on an emulator.
"""
import argparse
import hashlib
import importlib.util
import os
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import zipfile


TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
SHADOW_SOURCES = ROOT / "android-awt" / "src" / "main" / "java"
SHADOW_ROOTS = ("java", "javax", "sun", "com/sun")
APP_JAVA = ROOT / "android" / "src" / "androidMain" / "java" / "net" / "runelite" / "mp"
COMPAT = APP_JAVA / "compat"
TRANSFORM_SOURCES = [
    APP_JAVA / "plugins" / "PluginClassTransform.java",
    APP_JAVA / "plugins" / "IndyLowering.java",
    APP_JAVA / "client" / "SyntheticLambdas.java",
    COMPAT / "JdkRetargeter.java",
    *sorted((COMPAT / "jdk").glob("*.java")),
]
# The versions android/build.gradle.kts compiles the device transform and dexer against.
ASM_VERSION = "9.8"
R8_VERSION = "9.5.28"

# fixture -> (javac flags, bootstrap kinds its class files must hold). IndyCondyFixture is
# generated by TestIndyFixtures, since javac emits no ConstantBootstraps constant.
FIXTURES = {
    "IndyLambdaFixture": (["--release", "21"], ["LambdaMetafactory.metafactory"]),
    "IndyAltLambdaFixture": (["--release", "21"], [
        "LambdaMetafactory.altMetafactory[serializable]",
        "LambdaMetafactory.altMetafactory[markers]",
        "LambdaMetafactory.altMetafactory[bridges]",
    ]),
    "IndyConcatPlainFixture": (["--release", "21", "-XDstringConcat=indy"], ["StringConcatFactory.makeConcat"]),
    "IndyConcatConstantsFixture": (["--release", "11"], [
        "StringConcatFactory.makeConcatWithConstants",
        "StringConcatFactory.makeConcatWithConstants[constants]",
    ]),
    "IndyRecordFixture": (["--release", "21"], ["ObjectMethods.bootstrap"]),
    "IndyEnumSwitchFixture": (["--release", "21"], ["SwitchBootstraps.enumSwitch"]),
    "IndyTypeSwitchFixture": (["--release", "21"], ["SwitchBootstraps.typeSwitch"]),
    "IndyCondyFixture": (None, [
        "condy ConstantBootstraps.nullConstant",
        "condy ConstantBootstraps.primitiveClass",
        "condy ConstantBootstraps.enumConstant",
        "condy ConstantBootstraps.getStaticFinal",
        "condy ConstantBootstraps.invoke",
        "condy ConstantBootstraps.explicitCast",
    ]),
    "IndySelfCondyFixture": (None, ["condy IndySelfCondyFixture.$bootstrap"]),
}
# Fixtures with no javac flags come from TestIndyFixtures; this is its mode for each.
GENERATED = {"IndyCondyFixture": "condy", "IndySelfCondyFixture": "selfcondy"}
# Dex map item types ART at API 26 cannot use: invoke-custom call sites, and method handles
# (const-method-handle is API 28; a call site needs one for its bootstrap).
DEX_CALL_SITE_ID = 0x0007
DEX_METHOD_HANDLE = 0x0008


def load_inventory():
    spec = importlib.util.spec_from_file_location("indy_inventory", TOOLS / "indy-inventory.py")
    module = importlib.util.module_from_spec(spec)
    # Importing would otherwise leave tools-src/__pycache__ in the tree.
    sys.dont_write_bytecode = True
    spec.loader.exec_module(module)
    return module


def gradle_jar(group, artifact, version):
    base = Path.home() / ".gradle" / "caches" / "modules-2" / "files-2.1" / group / artifact / version
    jars = [j for j in base.rglob(f"{artifact}-{version}.jar")]
    if not jars:
        raise SystemExit(f"{group}:{artifact}:{version} is not in the Gradle cache ({base}); build :android once")
    return jars[0]


def android_jar(sdk):
    def level(path):
        match = re.search(r"android-(\d+)", path.parent.name)
        return int(match.group(1)) if match else 0
    jars = sorted((sdk / "platforms").glob("android-*/android.jar"), key=level)
    if not jars:
        raise SystemExit(f"no android.jar under {sdk / 'platforms'}")
    return jars[-1]


def dex_items(dex):
    """Counts of the dex map items DEX_CALL_SITE_ID and DEX_METHOD_HANDLE."""
    map_off = struct.unpack_from("<I", dex, 0x34)[0]
    size = struct.unpack_from("<I", dex, map_off)[0]
    counts = {}
    for i in range(size):
        kind, _, count, _ = struct.unpack_from("<HHII", dex, map_off + 4 + 12 * i)
        counts[kind] = count
    return counts.get(DEX_CALL_SITE_ID, 0), counts.get(DEX_METHOD_HANDLE, 0)


def jar_directory(directory, jar):
    with zipfile.ZipFile(jar, "w") as archive:
        for file in sorted(directory.rglob("*.class")):
            archive.write(file, file.relative_to(directory).as_posix())


class Runner:
    def __init__(self, out):
        self.out = out
        self.logs = []

    def __call__(self, label, *command, check=True, timeout=120):
        result = subprocess.run(list(map(str, command)), capture_output=True,
                                text=True, encoding="utf-8", errors="replace", timeout=timeout)
        message = f"[{label}] exit={result.returncode}\n{result.stdout}{result.stderr}"
        print(message, end="" if message.endswith("\n") else "\n", flush=True)
        self.logs.append(message)
        (self.out / "results.log").write_text("\n".join(self.logs), encoding="utf-8")
        if check and result.returncode:
            raise SystemExit(f"{label} failed with exit {result.returncode}")
        return result


def host_fixtures(args, out):
    inventory = load_inventory()
    suffix = ".exe" if os.name == "nt" else ""
    javac = args.java_home / "bin" / ("javac" + suffix)
    java = args.java_home / "bin" / ("java" + suffix)
    run = Runner(out)
    asm = [gradle_jar("org.ow2.asm", a, ASM_VERSION) for a in ("asm", "asm-commons", "asm-tree")]
    r8 = args.r8 or gradle_jar("com.android.tools", "r8", R8_VERSION)
    lib = android_jar(args.sdk)
    asm_cp = os.pathsep.join(map(str, asm))

    tools = out / "tools"
    if tools.exists():
        shutil.rmtree(tools)
    tools.mkdir(parents=True)
    run("compile transform", javac, "--release", "21", "-encoding", "UTF-8", "-cp", asm_cp, "-d", tools,
        *TRANSFORM_SOURCES, TOOLS / "TestIndyFixtures.java", TOOLS / "TestClientLambdaLowering.java",
        TOOLS / "TestRuntimeRetarget.java")
    tools_cp = os.pathsep.join([str(tools)] + [str(j) for j in asm])
    d8 = [java, "-cp", r8, "com.android.tools.r8.D8", "--release", "--min-api", "26", "--lib", lib]

    def dex_and_scan(label, jar, dex_dir):
        if dex_dir.exists():
            shutil.rmtree(dex_dir)
        dex_dir.mkdir(parents=True)
        run("D8 " + label, *d8, "--output", dex_dir, jar)
        dexes = sorted(dex_dir.glob("classes*.dex"))
        if not dexes:
            raise SystemExit(f"D8 wrote no dex for {label}")
        for dex in dexes:
            call_sites, handles = dex_items(dex.read_bytes())
            if call_sites or handles:
                raise SystemExit(f"{label}: {dex.name} keeps {call_sites} call sites and {handles} method handles")

    def same_output(label, raw, lowered):
        if "PASS:" not in raw.stdout:
            raise SystemExit(f"{label}: the host JVM run has no PASS marker")
        if raw.stdout != lowered.stdout:
            raise SystemExit(f"{label}: the transformed classes print differently from the originals")

    matrix = []
    for name, (flags, kinds) in FIXTURES.items():
        classes = out / "fixtures" / name
        if classes.exists():
            shutil.rmtree(classes)
        classes.mkdir(parents=True)
        if flags is None:
            run("generate " + name, java, "-cp", tools_cp, "TestIndyFixtures", GENERATED[name], classes)
        else:
            run("compile " + name, javac, *flags, "-encoding", "UTF-8", "-d", classes, TOOLS / (name + ".java"))
        found = inventory.inventory(classes)
        missing = [k for k in kinds if not inventory.covered(found, k)]
        if missing:
            raise SystemExit(f"{name} does not exercise {missing}; it holds {dict(found)}")

        raw_jar = out / "fixtures" / (name + ".jar")
        lowered_jar = out / "fixtures" / (name + "-transformed.jar")
        jar_directory(classes, raw_jar)
        run("transform " + name, java, "-Xverify:all", "-cp", tools_cp, "TestIndyFixtures", "transform", raw_jar, lowered_jar)
        # "condy " is an ldc; "condy-arg " (typeSwitch EnumDesc labels) goes with its call site to D8.
        left = {k: n for k, n in inventory.jar_bootstraps(lowered_jar).items() if k.startswith("condy ")}
        if left:
            raise SystemExit(f"{name}: PluginClassTransform left {left}")

        raw = run("run " + name, java, "-cp", classes, name)
        lowered = run("run transformed " + name, java, "-Xverify:all", "-cp", lowered_jar, name)
        same_output(name, raw, lowered)
        dex_and_scan(name, lowered_jar, out / "dex" / name)
        if flags is None:
            # Not a pass condition, a record of why the lowering exists.
            untouched = run("D8 untransformed " + name, *d8, "--output", out / "dex" / (name + "-raw.zip"), raw_jar, check=False)
            print(f"  D8 on the untransformed constants: {'refused' if untouched.returncode else 'accepted'}")
        matrix.append((name, sorted(found)))

    # DesugarLambdasTask's private-method lowering: H_INVOKESPECIAL impls dispatched INVOKEVIRTUAL.
    name = "ClientLambdaFixture"
    raw_dir = out / "fixtures" / name
    lowered_dir = out / "fixtures" / (name + "-lowered")
    for d in (raw_dir, lowered_dir):
        if d.exists():
            shutil.rmtree(d)
        d.mkdir(parents=True)
    run("compile " + name, javac, "--release", "8", "-encoding", "UTF-8", "-d", raw_dir, TOOLS / (name + ".java"))
    run("lower " + name, java, "-cp", tools_cp, "TestClientLambdaLowering", raw_dir, lowered_dir)
    if inventory.inventory(lowered_dir):
        raise SystemExit(f"{name}: lowered classes still hold {dict(inventory.inventory(lowered_dir))}")
    raw = run("run " + name, java, "-cp", raw_dir, name)
    lowered = run("run lowered " + name, java, "-Xverify:all", "-cp", lowered_dir, name)
    same_output(name, raw, lowered)
    lowered_jar = out / "fixtures" / (name + "-lowered.jar")
    jar_directory(lowered_dir, lowered_jar)
    dex_and_scan(name, lowered_jar, out / "dex" / name)
    matrix.append((name, ["LambdaMetafactory.metafactory (client pass)"]))

    # JdkRetargets fixture: a --release 11 plugin calling table members, directly and through
    # method references, goes through PluginClassTransform; TestRuntimeRetarget checks no row,
    # relocated type or String regex call is left, then the rewritten plugin runs under
    # -Xverify:all against the shims, the desktop regex engine and DesktopRegexStrings compiled
    # from the app's sources, so every retargeted call site links to a real member.
    name = "TestRuntimeRetargetPlugin"
    plugin_dir = out / "fixtures" / name
    runtime_dir = out / "fixtures" / "retarget-runtime"
    for d in (plugin_dir, runtime_dir):
        if d.exists():
            shutil.rmtree(d)
        d.mkdir(parents=True)
    run("compile " + name, javac, "--release", "11", "-encoding", "UTF-8", "-d", plugin_dir, TOOLS / (name + ".java"))
    plugin_jar = out / "retarget-plugin.jar"
    rewritten_jar = out / "retarget-rewritten.jar"
    jar_directory(plugin_dir, plugin_jar)
    retarget = run("retarget " + name, java, "-Xverify:all", "-cp", tools_cp, "TestRuntimeRetarget", plugin_jar, rewritten_jar)
    if "PASS:" not in retarget.stdout:
        raise SystemExit("TestRuntimeRetarget printed no PASS marker")
    # android.jar is compile-only: Pattern names android.icu for CANON_EQ, which the fixture
    # never sets, so nothing from it loads on the JVM.
    run("compile retarget runtime", javac, "-encoding", "UTF-8", "-nowarn",
        "-cp", os.pathsep.join([str(tools), str(lib)]), "-d", runtime_dir,
        APP_JAVA / "plugins" / "DesktopRegexStrings.java", *sorted((COMPAT / "regex").glob("*.java")))
    linked = run("run retargeted " + name, java, "-Xverify:all",
                 "-cp", os.pathsep.join(map(str, (tools, runtime_dir, rewritten_jar))), name)
    if "PASS:" not in linked.stdout:
        raise SystemExit(f"{name}: the retargeted plugin printed no PASS marker")
    dex_and_scan(name, rewritten_jar, out / "dex" / name)
    matrix.append((name, ["JdkRetargets rows + desktop regex (PluginClassTransform)"]))

    print(f"PASS: {len(matrix)} fixtures transformed, verified on the host JVM and dexed at min-api 26")
    for fixture, kinds in matrix:
        print(f"  {fixture}: {', '.join(kinds)}")


def check_host_api(host_api):
    """Every top-level shadow class android-awt compiles must be in host-api.jar, the library
    the on-device D8 resolves hub plugins against; a class missing there dexes into a call the
    APK cannot link. Inner classes follow their outer source file, so sources are the oracle."""
    with zipfile.ZipFile(host_api) as archive:
        classes = {name for name in archive.namelist() if name.endswith(".class")}
    missing = []
    for source in sorted(SHADOW_SOURCES.rglob("*.java")):
        relative = source.relative_to(SHADOW_SOURCES).as_posix()
        if relative.startswith(tuple(root + "/" for root in SHADOW_ROOTS)) and source.stem != "package-info":
            if relative[:-len(".java")] + ".class" not in classes:
                missing.append(relative)
    outside = sorted(name for name in classes if not name.startswith(tuple(root + "/" for root in SHADOW_ROOTS)))
    print(f"[host-api.jar] {len(classes)} classes; missing shadow classes: {len(missing)}; outside the shadow: {len(outside)}")
    for name in missing + outside:
        print("  " + name)
    if missing or outside:
        raise SystemExit("host-api.jar does not match the shadow surface")


def emulator_link(args, out):
    if not re.fullmatch(r"emulator-\d+", args.serial):
        raise SystemExit("This probe only targets an emulator.")
    suffix = ".exe" if os.name == "nt" else ""
    java = args.java_home / "bin"
    adb = args.sdk / "platform-tools" / ("adb" + suffix)
    r8 = args.r8 or gradle_jar("com.android.tools", "r8", R8_VERSION)
    logs = []

    def run(label, *command, expected_failure=False):
        result = subprocess.run(list(map(str, command)), capture_output=True,
                                text=True, encoding="utf-8", errors="replace", timeout=300 if label.startswith("push ") else 120)
        message = f"[{label}] exit={result.returncode}\n{result.stdout}{result.stderr}"
        print(message, end="", flush=True)
        logs.append(message)
        (out / "emulator.log").write_text("\n".join(logs), encoding="utf-8")
        if expected_failure:
            if result.returncode == 0 or "NoSuchMethodError" not in result.stdout + result.stderr:
                raise SystemExit("Expected the old conversion to expose the Flow ABI mismatch")
        elif result.returncode:
            raise SystemExit(result.returncode)
        return result.stdout + result.stderr

    with zipfile.ZipFile(args.apk) as archive:
        manifest = dict(line.split("=", 1) for line in archive.read("assets/runtime-dex/inputs.properties")
                        .decode().splitlines() if "=" in line)
        for name in ("desugar.json", "java-api.jar", "host-api.jar"):
            data = archive.read("assets/runtime-dex/" + name)
            if hashlib.sha256(data).hexdigest() != manifest["sha256." + name]:
                raise SystemExit("Compiler asset hash mismatch: " + name)
            (out / name).write_bytes(data)
    check_host_api(out / "host-api.jar")
    (out / "apk-sha256.txt").write_text(hashlib.sha256(args.apk.read_bytes()).hexdigest() + "\n")
    classes = out / "classes"
    classes.mkdir(exist_ok=True)
    run("compile desktop plugin", java / ("javac" + suffix), "--release", "11", "-d", classes,
        TOOLS / "TestRuntimeHttpPlugin.java")
    run("package JVM fixture", java / ("jar" + suffix), "cf", out / "plugin.jar", "-C", classes, ".")
    compiler = [java / ("java" + suffix), "-cp", r8, "com.android.tools.r8.D8",
                "--release", "--min-api", "26"]
    run("old D8 conversion", *compiler, "--output", out / "old.jar", out / "plugin.jar")
    run("aligned D8 conversion", *compiler, "--desugared-lib", out / "desugar.json",
        "--lib", out / "java-api.jar", "--classpath", out / "host-api.jar",
        "--output", out / "aligned.jar", out / "plugin.jar")
    run("retarget D8 conversion", *compiler, "--desugared-lib", out / "desugar.json",
        "--lib", out / "java-api.jar", "--classpath", out / "host-api.jar",
        "--output", out / "retarget.jar", out / "retarget-rewritten.jar")

    remote = "/data/local/tmp/runtime-plugin-contracts"
    run("prepare emulator fixture", adb, "-s", args.serial, "shell", "mkdir", "-p", remote)
    for local, name in ((args.apk, "host.apk"), (out / "old.jar", "old.jar"), (out / "aligned.jar", "aligned.jar"),
                        (out / "retarget.jar", "retarget.jar")):
        run("push " + name, adb, "-s", args.serial, "push", local, remote + "/" + name)
    for name, main_class, negative in (("old.jar", "TestRuntimeHttpPlugin", True),
                                       ("aligned.jar", "TestRuntimeHttpPlugin", False),
                                       ("retarget.jar", "TestRuntimeRetargetPlugin", False)):
        result = run("link " + name, adb, "-s", args.serial, "shell",
                     f"CLASSPATH={remote}/host.apk:{remote}/{name}", "dalvikvm", main_class,
                     expected_failure=negative)
        if not negative and "PASS:" not in result:
            raise SystemExit("Missing fixture success marker")
    run("remove temporary host copy", adb, "-s", args.serial, "shell", "rm", remote + "/host.apk")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    default_jdk = os.environ.get("JAVA_HOME") or r"C:\Program Files\Java\jdk-21.0.10"
    default_sdk = Path(os.environ.get("LOCALAPPDATA", str(Path.home()))) / "Android" / "Sdk"
    parser.add_argument("--java-home", type=Path, default=Path(default_jdk), help="JDK 21 or newer")
    parser.add_argument("--sdk", type=Path, default=Path(os.environ.get("ANDROID_HOME") or default_sdk))
    parser.add_argument("--r8", type=Path, help=f"r8.jar (default: r8-{R8_VERSION} from the Gradle cache)")
    parser.add_argument("--output", type=Path, default=ROOT / "build" / "runtime-plugin-dex")
    parser.add_argument("--apk", type=Path, help="with --serial: also run the emulator link probe")
    parser.add_argument("--serial")
    args = parser.parse_args()
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=True)
    host_fixtures(args, out)
    if args.apk or args.serial:
        if not (args.apk and args.serial):
            raise SystemExit("--apk and --serial go together")
        emulator_link(args, out)


if __name__ == "__main__":
    main()
